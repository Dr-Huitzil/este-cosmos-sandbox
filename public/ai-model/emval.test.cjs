const fs = require('fs');
const assert = require('assert');

const wasmBuffer = fs.readFileSync(__dirname + '/edge-impulse-standalone.wasm');
let code = fs.readFileSync(__dirname + '/edge-impulse-standalone.js', 'utf8');

// Inject our functional test inside the code string so it runs in the same scope
// and has access to internal variables like count_emval_handles and registeredTypes.
const testCode = `
  Module['test_emval_interface'] = function() {
    var emvalType;
    for (var k in registeredTypes) {
      if (registeredTypes[k].name === 'emscripten::val') {
         emvalType = registeredTypes[k];
         break;
      }
    }
    if (!emvalType) throw new Error("emscripten::val type not found");

    var initialCount = count_emval_handles();

    // Simulate passing a JS object via emval
    var myObj = { method: function() { console.log('called'); } };
    var handle = Emval.toHandle(myObj);

    // Simulate method caller pointer arg
    var ptr = _malloc(4);
    HEAPU32[ptr >> 2] = handle;

    var args = ptr;

    // Interface logic: read value and parse it
    var arg0 = emvalType.readValueFromPointer(args);

    // arg0 should be myObj
    if (arg0 !== myObj) throw new Error("arg0 does not match myObj");

    // Cleanup generated by __emval_get_method_caller
    if (emvalType.deleteObject) {
       emvalType.deleteObject(arg0);
    }

    // handle count should return to initialCount because fromWireType decrements it
    var finalCount = count_emval_handles();
    if (finalCount !== initialCount) {
       throw new Error("Memory leak! Handles: " + finalCount + " vs " + initialCount);
    }

    _free(ptr);
    return true;
  };
`;
// Append to code
code = code + "\n" + testCode + "\n";

const context = {
  window: {},
  document: { currentScript: { src: 'edge-impulse-standalone.js' } },
  console: console,
  setTimeout: setTimeout,
  clearTimeout: clearTimeout,
  setInterval: setInterval,
  clearInterval: clearInterval,
  URL: URL,
  process: { browser: true },
  require: undefined,
  Module: {
    wasmBinary: wasmBuffer,
    onRuntimeInitialized: function() {
      try {
        const success = context.Module.test_emval_interface();
        assert.ok(success, "test_emval_interface failed");
        console.log("WebAssembly loaded successfully.");
        console.log("Emval interface test passed: memory safety asserted. No handle leak occurred without deleteObject.");
      } catch (err) {
        console.error("Test failed:", err);
        process.exit(1);
      }
    }
  }
};
context.self = context.window;

const vm = require('vm');
vm.createContext(context);
vm.runInContext("var Module = Module || {};", context);
vm.runInContext(code, context);
